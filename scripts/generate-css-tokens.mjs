#!/usr/bin/env node
// Generates apps/web/app/theme-tokens.css FROM packages/ui/src/tokens.ts, so
// the web app never hand-copies color values -- there is exactly one source
// of truth for the design system, shared by React Native (as JS objects)
// and Next.js (as CSS variables). Run with: `npx tsx scripts/generate-css-tokens.mjs`
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { themes, spacing, radii, fonts } from '../packages/ui/src/tokens.ts';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const outPath = path.join(__dirname, '..', 'apps', 'web', 'app', 'theme-tokens.css');

function colorVars(colors) {
  return [
    `  --background: ${colors.background};`,
    `  --surface: ${colors.surface};`,
    `  --surface-elevated: ${colors.surfaceElevated};`,
    `  --border: ${colors.border};`,
    `  --text-primary: ${colors.textPrimary};`,
    `  --text-muted: ${colors.textMuted};`,
    `  --accent: ${colors.accent};`,
    `  --ai: ${colors.ai};`,
    `  --success: ${colors.success};`,
    `  --warning: ${colors.warning};`,
    `  --danger: ${colors.danger};`,
  ].join('\n');
}

const spacingVars = Object.entries(spacing)
  .map(([key, value]) => `  --space-${key}: ${value}px;`)
  .join('\n');

const radiiVars = Object.entries(radii)
  .map(([key, value]) => `  --radius-${key}: ${value}px;`)
  .join('\n');

const css = `/* AUTO-GENERATED by scripts/generate-css-tokens.mjs from packages/ui/src/tokens.ts.
   Do not edit by hand -- edit tokens.ts and regenerate. */

:root {
${colorVars(themes.light)}
${spacingVars}
${radiiVars}
  --font-family: '${fonts.family}', system-ui, sans-serif;
  --font-mono: '${fonts.mono}', ui-monospace, monospace;
}

@media (prefers-color-scheme: dark) {
  :root {
${colorVars(themes.dark)}
  }
}
`;

writeFileSync(outPath, css, 'utf8');
console.log(`Wrote ${outPath} (${css.length} bytes) from packages/ui/src/tokens.ts`);
